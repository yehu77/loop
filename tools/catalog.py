"""Read-only experiment navigation. Standard library only; never launches runs."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "docs/experiments/catalog.json"
INDEX = ROOT / "docs/experiments/README.md"


def repo_path(value):
    path = Path(value)
    if not path.parts or path.is_absolute() or ".." in path.parts or path.parts[0] in (".git", ".aws", ".codex", ".agents"):
        raise ValueError("Not a project path: " + value)
    resolved = (ROOT / path).resolve()
    if not resolved.is_relative_to(ROOT):
        raise ValueError("Path leaves repository: " + value)
    return resolved


def load_catalog():
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    if data.get("schema_version") != 1 or not data.get("experiments"):
        raise ValueError("Unsupported or empty catalog")
    seen = set()
    for entry in data["experiments"]:
        identifier = entry["id"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", identifier) or identifier in seen:
            raise ValueError("Invalid or duplicate experiment ID: " + identifier)
        seen.add(identifier)
        if entry["status"] not in ("planned", "running", "archived"):
            raise ValueError("Invalid status: " + identifier)
        for name in ("title", "conclusion"):
            if not isinstance(entry[name], str) or not entry[name].strip():
                raise ValueError("Missing " + name + ": " + identifier)
        for field in ("configs", "local_outputs", "seeds"):
            if not isinstance(entry[field], list) or len(entry[field]) != len(set(entry[field])):
                raise ValueError("Invalid " + field + ": " + identifier)
        for path in [entry["report"], entry["archive"], *entry["configs"], *entry["local_outputs"]]:
            repo_path(path)
        if not all(p.startswith("outputs/") for p in entry["local_outputs"]):
            raise ValueError("Local runs must be under outputs/: " + identifier)
    return data


def markdown(data):
    lines = ["# 实验目录", "", "<!-- Generated by python tools/catalog.py list --markdown; edit catalog.json. -->", "",
             "[返回文档首页](../README.md) · [复现说明](../guide/reproduction.md)", "",
             "截至 " + data["as_of"] + "。" + data["status_note"], "",
             "## 按研究问题查找", "",
             "| ID | 实验 | 状态 | 验证日 / 种子 | 已有判断 |", "|---|---|---|---|---|"]
    for e in data["experiments"]:
        link = "../../" + e["report"]
        seeds = ", ".join(map(str, e["seeds"]))
        lines.append(f"| `{e['id']}` | [{e['title']}]({link}) | {e['status']} | {e['validation_days']} / {seeds} | {e['conclusion']} |")
    lines += ["", "## 配置、归档与本地产物", "",
              "以下路径以仓库根目录为基准。本地产物不随 Git 克隆分发；目录存在也不代表完整性校验通过。",
              "", "```bash", "python tools/catalog.py show prediction-correction --local", "python tools/catalog.py check", "```"]
    for e in data["experiments"]:
        lines += ["", "### " + e["id"], "", f"- 归档：[{e['archive']}](../../{e['archive']}/)"]
        for path in e["configs"]:
            lines.append(f"- 配置：[{path}](../../{path})")
        if not e["configs"]:
            lines.append("- 原运行配置已保存在对应归档目录；以报告中的来源和命令为准。")
        lines.append("- 本地运行：" + "、".join("`" + p + "`" for p in e["local_outputs"]))
    lines += ["", "当前元数据只服务于导航，不参与模型、采样、检查点身份或实验结果计算。",
              "新增实验时修改 [catalog.json](catalog.json)，再执行：", "",
              "```bash", "python tools/catalog.py list --markdown > docs/experiments/README.md",
              "python tools/catalog.py check", "```", ""]
    return "\n".join(lines)


def check(data):
    errors = []
    for e in data["experiments"]:
        for path in [e["report"], e["archive"], *e["configs"]]:
            if not repo_path(path).exists():
                errors.append(e["id"] + ": missing " + path)
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != markdown(data):
        errors.append("Experiment README is stale; regenerate with list --markdown")
    if errors:
        raise ValueError("\n".join(errors))
    print(f"OK: {len(data['experiments'])} experiments; tracked references and generated index match.")
    print("Local outputs are optional. This checks navigation, not scientific results or checkpoint hashes.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    listing = sub.add_parser("list", help="List research questions and archived conclusions")
    listing.add_argument("--local", action="store_true", help="Report local directory presence only")
    listing.add_argument("--markdown", action="store_true", help="Print the generated Markdown index")
    show = sub.add_parser("show", help="Show report/config/artifact paths for one experiment")
    show.add_argument("id")
    show.add_argument("--local", action="store_true")
    sub.add_parser("check", help="Check tracked references and index freshness; no torch needed")
    args = parser.parse_args()
    try:
        data = load_catalog()
        if args.command == "check":
            check(data)
            return
        if args.command == "list" and args.markdown:
            print(markdown(data), end="")
            return
        entries = data["experiments"]
        if args.command == "show":
            entries = [e for e in entries if e["id"] == args.id]
            if not entries:
                raise ValueError("Unknown experiment: " + args.id)
        for e in entries:
            print(f"{e['id']} [{e['status']}] {e['title']}")
            print("  " + e["conclusion"])
            print("  report: " + e["report"])
            if args.command == "show":
                print("  archive: " + e["archive"])
                for path in e["configs"]:
                    print("  config: " + path)
            if args.local:
                for path in e["local_outputs"]:
                    state = "present" if repo_path(path).is_dir() else "missing (local only)"
                    print(f"  {state}: {path}")
    except (ValueError, KeyError, TypeError, OSError) as error:
        print(str(error), file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
